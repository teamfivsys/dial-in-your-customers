import assert from "node:assert/strict";
import { readFileSync, existsSync } from "node:fs";
const html = readFileSync("dist/index.html", "utf8");
assert.equal((html.match(/<h1[ >]/g) || []).length, 1, "Exactly one H1");
assert.match(html, /<h1>Kerala business<br\/>directory\.<br\/><em>Coming soon\.<\/em><\/h1>/);
assert.equal((html.match(/rel="canonical"/g) || []).length, 1, "Single canonical");
assert.match(html, /rel="canonical" href="https:\/\/kdial.in\/"/);
assert.equal((html.match(/name="description"/g) || []).length, 1);
assert.equal((html.match(/name="robots"/g) || []).length, 1);
assert.doesNotMatch(html, /noindex|SearchAction|AggregateRating|priceValidUntil|₹501\/year|locked forever|₹2,999/);
assert.match(html, /Launch planned · 1 November 2026/);
assert.match(html, /Kochi in Ernakulam district/);
assert.match(html, /This opens WhatsApp/);
assert.match(html, /https:\/\/wa.me\/917356137106\?text=/);
const scripts = [...html.matchAll(/<script[^>]*type="application\/ld\+json"[^>]*>([\s\S]*?)<\/script>/g)];
assert.equal(scripts.length, 1, "Structured data is present in raw HTML");
const graph = JSON.parse(scripts[0][1])["@graph"];
assert.deepEqual(graph.map(item => item["@type"]), ["Organization", "WebSite", "WebPage"]);
const sitemap = readFileSync("dist/sitemap.xml", "utf8");
assert.equal((sitemap.match(/<loc>/g) || []).length, 1);
assert.match(sitemap, /<loc>https:\/\/kdial.in\/<\/loc>/);
const robots = readFileSync("dist/robots.txt", "utf8");
assert.match(robots, /User-agent: \*/);
assert.doesNotMatch(robots, /Disallow: \/\*\?\*/);
assert.match(robots, /Sitemap: https:\/\/kdial.in\/sitemap.xml/);
assert.ok(existsSync("dist/og-image.png"));
assert.doesNotMatch(readFileSync("dist/llms.txt", "utf8"), /₹501\/year|₹2,999|first 100/);
console.log("PASS: raw HTML content, canonical, metadata, JSON-LD, pre-launch terms, enquiry link, sitemap, robots and social image");
